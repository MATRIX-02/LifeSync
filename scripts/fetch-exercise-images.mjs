// One-off: matches src/data/exerciseDatabase.ts names against free-exercise-db
// (Unlicense/public domain) and emits an id -> image URL map for review.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DB_PATH = resolve(ROOT, "src/data/exerciseDatabase.ts");
const OUT_PATH = resolve(ROOT, "src/data/exerciseImages.ts");
const REPORT_PATH = resolve(ROOT, "scripts/exercise-image-report.json");

const SOURCE_JSON =
	"https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json";
const IMAGE_BASE =
	"https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/";

// Accept a match only when the two names are this similar (0-1).
const MIN_SCORE = 0.62;

// Reviewed and rejected: the source depicts a different movement, which matters
// more for the rehab entries than a missing image does.
const REJECTED = new Set([
	"ex_double_knee_to_chest",
	"ex_pelvic_tilt",
	"ex_standing_extension",
]);

const normalize = (s) =>
	s
		.toLowerCase()
		.replace(/[^a-z0-9\s]/g, " ")
		.replace(/\s+/g, " ")
		.trim();

// Words that carry no distinguishing signal between exercise names.
const STOP = new Set([
	"the",
	"a",
	"with",
	"and",
	"on",
	"to",
	"for",
	"of",
	"using",
	"exercise",
]);

// Vocabulary differences between the two datasets.
const SYNONYMS = {
	pushup: "push up",
	pushups: "push up",
	pullup: "pull up",
	pullups: "pull up",
	chinup: "chin up",
	situp: "sit up",
	situps: "sit up",
	dumbbells: "dumbbell",
	flyes: "fly",
	flys: "fly",
	flye: "fly",
	flies: "fly",
	crunches: "crunch",
	raises: "raise",
	curls: "curl",
	extensions: "extension",
	lunges: "lunge",
	presses: "press",
	rows: "row",
	squats: "squat",
	deadlifts: "deadlift",
	ab: "abdominal",
	abs: "abdominal",
	bicep: "biceps",
	tricep: "triceps",
};

const tokens = (name) =>
	normalize(name)
		.split(" ")
		.flatMap((w) => (SYNONYMS[w] ?? w).split(" "))
		.filter((w) => w && !STOP.has(w));

// Dice coefficient over token sets, nudged up when one name contains the other.
function score(a, b) {
	const A = new Set(tokens(a));
	const B = new Set(tokens(b));
	if (!A.size || !B.size) return 0;

	let shared = 0;
	for (const t of A) if (B.has(t)) shared += 1;
	let s = (2 * shared) / (A.size + B.size);

	const na = normalize(a);
	const nb = normalize(b);
	if (na === nb) return 1;
	if (na.includes(nb) || nb.includes(na)) s = Math.max(s, 0.85);

	return s;
}

// Pulls `id` / `name` pairs straight out of the TS literal; no transpile needed.
function readLocalExercises() {
	const src = readFileSync(DB_PATH, "utf8");
	const re = /id:\s*"(ex_[^"]+)"\s*,\s*\n\s*name:\s*"([^"]+)"/g;
	const out = [];
	let m;
	while ((m = re.exec(src)) !== null) out.push({ id: m[1], name: m[2] });
	return out;
}

async function main() {
	const local = readLocalExercises();
	if (local.length === 0) {
		throw new Error(`No exercises parsed from ${DB_PATH}`);
	}
	console.log(`Parsed ${local.length} local exercises.`);

	const res = await fetch(SOURCE_JSON);
	if (!res.ok) throw new Error(`Fetch failed: ${res.status} ${res.statusText}`);
	const remote = await res.json();
	console.log(`Fetched ${remote.length} remote exercises.`);

	const matched = [];
	const unmatched = [];

	for (const ex of local) {
		let best = null;
		let bestScore = 0;

		for (const cand of remote) {
			if (!cand.images?.length) continue;
			const s = score(ex.name, cand.name);
			if (s > bestScore) {
				bestScore = s;
				best = cand;
			}
		}

		if (best && bestScore >= MIN_SCORE && !REJECTED.has(ex.id)) {
			matched.push({
				id: ex.id,
				localName: ex.name,
				matchedName: best.name,
				score: Number(bestScore.toFixed(3)),
				images: best.images.map((p) => IMAGE_BASE + p),
			});
		} else {
			unmatched.push({
				id: ex.id,
				localName: ex.name,
				closest: best?.name ?? null,
				score: Number(bestScore.toFixed(3)),
			});
		}
	}

	const entries = [...matched]
		.sort((a, b) => a.id.localeCompare(b.id))
		.map(
			(m) =>
				`\t// ${m.matchedName} (${m.score})\n` +
				`\t${m.id}: [\n` +
				m.images.map((u) => `\t\t"${u}",`).join("\n") +
				`\n\t],`,
		)
		.join("\n");

	const file = `// AUTO-GENERATED by scripts/fetch-exercise-images.mjs - do not edit by hand.
// Source: https://github.com/yuhonas/free-exercise-db (Unlicense / public domain)
// Images are start/end position frames, in order.

export const EXERCISE_IMAGES: Record<string, string[]> = {
${entries}
};

export const getExerciseImages = (exerciseId: string): string[] =>
	EXERCISE_IMAGES[exerciseId] ?? [];
`;

	writeFileSync(OUT_PATH, file, "utf8");
	writeFileSync(
		REPORT_PATH,
		JSON.stringify({ matched, unmatched }, null, 2),
		"utf8",
	);

	console.log(`\nMatched:   ${matched.length}`);
	console.log(`Unmatched: ${unmatched.length}`);
	console.log(`\nWrote ${OUT_PATH}`);
	console.log(`Review low-confidence matches in ${REPORT_PATH}`);

	const weak = matched
		.filter((m) => m.score < 0.8)
		.sort((a, b) => a.score - b.score);
	if (weak.length) {
		console.log(`\n${weak.length} match(es) below 0.8 - verify these:`);
		for (const m of weak) {
			console.log(`  ${m.score}  "${m.localName}" -> "${m.matchedName}"`);
		}
	}
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
